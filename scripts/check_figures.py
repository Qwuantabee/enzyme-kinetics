#!/usr/bin/env python3
"""Did regenerating the figures change their LAYOUT, or only their rendering?

The question this answers, and the two wrong answers I tried first.

Attempt 1: `git diff --exit-code -- figures/`. Failed on all three repos with
`Bin 142376 -> 142376 bytes` - same size, different bytes - because matplotlib
writes its own version into a tEXt chunk. That check tested the matplotlib
version, not the figure.

Attempt 2: compare decoded pixel arrays. That failed too, and the CI log is the
proof: every one of the 11 enzyme figures reported "pixels differ" on the
runner while being identical locally. Rendering is not portable - matplotlib
version, freetype, and the installed font set all change anti-aliasing and glyph
shapes. Pixel identity across machines is not an achievable invariant, so a
check that demands it can only ever go red.

What IS portable, and what this checks: image dimensions. A figure whose axes,
panel count, or drawn extent changed comes out a different size, and that is
exactly the drift worth blocking - it means the committed PNG no longer matches
the code and data that produced it. Same dimensions with different pixels is
rendering noise and is reported, not failed.

Usage:
    python scripts/check_figures.py [--dir figures] [--strict]

    --strict  also fail on pixel differences (only meaningful when the
              regenerating machine matches the one that committed the figures;
              never use it in CI)
"""
import argparse
import io
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def head_bytes(rel: str):
    p = subprocess.run(["git", "show", f"HEAD:{rel}"], cwd=ROOT,
                       capture_output=True)
    return p.stdout if p.returncode == 0 else None


def changed_pngs(figdir: str):
    p = subprocess.run(["git", "status", "--porcelain", "--", figdir], cwd=ROOT,
                       capture_output=True, text=True)
    out = []
    for line in p.stdout.splitlines():
        if not line.strip():
            continue
        status, path = line[:2].strip(), line[3:]
        if path.endswith(".png"):
            out.append((status, path))
    return out


def size_of(blob):
    im = Image.open(io.BytesIO(blob))
    return im.size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="figures")
    ap.add_argument("--strict", action="store_true")
    args = ap.parse_args()

    changes = changed_pngs(args.dir)
    if not changes:
        print(f"{args.dir}/: every PNG regenerated byte-identically.")
        return 0

    layout, render, broken = [], [], []
    for status, rel in changes:
        if status == "D":
            broken.append((rel, "the regeneration deleted this figure"))
            continue
        old = head_bytes(rel)
        if old is None:
            broken.append((rel, "not present in the commit"))
            continue
        try:
            old_size = size_of(old)
        except Exception as exc:                                  # noqa: BLE001
            broken.append((rel, f"committed blob will not decode: {exc}"))
            continue
        try:
            new_size = size_of((ROOT / rel).read_bytes())
        except Exception as exc:                                  # noqa: BLE001
            broken.append((rel, f"regenerated file will not decode: {exc}"))
            continue
        if old_size != new_size:
            layout.append((rel, f"{old_size[0]}x{old_size[1]} -> "
                                f"{new_size[0]}x{new_size[1]}"))
        else:
            render.append(rel)

    if render:
        print(f"{len(render)} figure(s) differ only in rendering (same "
              f"dimensions) - normal across machines:")
        for rel in render:
            print(f"  {rel}")

    if layout:
        print("\nLAYOUT CHANGED. These figures no longer match the code and "
              "data that produced them:")
        for rel, why in layout:
            print(f"  {rel}: {why}")
        print("\nRe-commit the regenerated PNGs if the change is intended.")

    if broken:
        print("\nBROKEN. The regeneration did not reproduce these figures:")
        for rel, why in broken:
            print(f"  {rel}: {why}")

    if layout or broken:
        return 1

    if args.strict and render:
        print("\n--strict: treating rendering differences as failures.")
        return 1

    print("\nno layout change; nothing to commit.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
